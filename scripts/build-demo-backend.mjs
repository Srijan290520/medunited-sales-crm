// Wraps the real apps-script/*.gs files into one ES module so the preview
// build can run the actual backend in the browser (src/demo/). Not used by
// the production build.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'apps-script');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.gs')).sort();
const body = files.map((f) => `// ---- ${f} ----\n${fs.readFileSync(path.join(dir, f), 'utf8')}`).join('\n\n');
const out = `// GENERATED by scripts/build-demo-backend.mjs from apps-script/*.gs — do not edit.
/* eslint-disable */
// @ts-nocheck
export function createGasBackend(SpreadsheetApp, CacheService, LockService, PropertiesService, ContentService, DriveApp, Utilities, Logger, console) {
${body}
  return { doPost, setupSpreadsheet, createFirstAdmin };
}
`;
fs.writeFileSync(path.join(root, 'src', 'demo', 'gasBackend.generated.js'), out);
console.log(`demo backend: ${files.length} files wrapped`);
